"""Avalia somente arquivos de previsões piloto, rejeitando fold 10."""
import json
import sys
from pathlib import Path
import numpy as np
import pandas as pd
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/"src"))
from datamind.pilot import allowed
from datamind.evaluation import summarize,cluster_intervals,paired,metrics
def write(p,obj):
    p.write_text(json.dumps(obj,indent=2,ensure_ascii=False,allow_nan=False),encoding="utf-8")
def main():
    cfg=json.loads((ROOT/"experiments/fase5.json").read_text())
    out=ROOT/cfg["output"]
    source=pd.read_csv(ROOT/"data/raw/phase3/ptbxl_database.csv")
    source=source[source.strat_fold.le(9)]
    provenance={}
    for name,g in [("dev",source[source.strat_fold.le(8)]),("val",source[source.strat_fold.eq(9)])]:
        provenance[name]={c:{str(k):int(v) for k,v in g[c].value_counts(dropna=False).items()}
                          for c in ["initial_autogenerated_report","validated_by_human","second_opinion"]}
    write(out/"annotation_provenance.json",provenance)
    result={}
    cohorts={}
    for filename in ["oof_fixed","oof_selected","validation"]:
        frame=pd.read_csv(out/(filename+".csv"))
        allowed(frame)
        arms=[a for a in ["B0","E1","E2-C","E2","E2-fallback","E3","E3-I","Hybrid","E1_C1","E2-C_C1"] if a in frame]
        row={"overall":summarize(frame,arms),"strata":{},"paired":{},"folds":{}}
        for fold,g in frame.groupby("strat_fold"):
            row["folds"][str(fold)]=summarize(g,arms)
        for label,mask in [("complete",frame.complete),("incomplete",~frame.complete)]:
            g=frame[mask]
            row["strata"][label]=summarize(g,arms if label=="complete" else [a for a in arms if not a.startswith("E1")])
            # Privacy age values are not physiological ages; exclude >89 from summaries.
            age=g.age.where(g.age<=89)
            cohorts[filename+"_"+label]={"n":len(g),"patients":int(g.patient_id.nunique()),
                "positive":int(g.y.sum()),"prevalence":float(g.y.mean()),
                "age_median_under90":float(age.median()),"age_missing_or_masked":int(age.isna().sum()),
                "sex_counts":{str(k):int(v) for k,v in g.sex.value_counts(dropna=False).items()},
                "device_counts":{str(k):int(v) for k,v in g.device.value_counts(dropna=False).items()},
                "site_counts":{str(k):int(v) for k,v in g.site.value_counts(dropna=False).items()}}
        for a,b,mask in [("E3","E2-fallback",None),("E3-I","E3",None),("Hybrid","E2-fallback",None),
                         ("E1","E2-C",frame.complete),("E2-C","E2",frame.complete)]:
            row["paired"][a+" minus "+b]=paired(frame,a,b,mask)
        if filename=="validation":
            row["paired"]["E1_C1 minus E2-C_C1"]=paired(frame,"E1_C1","E2-C_C1",frame.complete)
            thresholds=json.loads((out/"thresholds.json").read_text())
            row["threshold_fit_apparent"]={}
            for a,t in thresholds.items():
                if t is not None:
                    g=frame[frame[a].notna()]
                    row["threshold_fit_apparent"][a]={"threshold":t,**metrics(g.y,g[a],t)}
        # OOF selected C is a selection diagnostic, not separately bootstrapped.
        if filename!="oof_selected":
            print("Bootstrap "+filename,flush=True)
            row["bootstrap"]=cluster_intervals(frame,arms,cfg["bootstrap"],cfg["seed"],filename=="validation")
        result[filename]=row
    write(out/"evaluation.json",result)
    write(out/"composition.json",cohorts)
    print("Evaluation complete, no fold 10",flush=True)
if __name__=="__main__":main()
